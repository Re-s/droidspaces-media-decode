/* Log switches only read once. Driver is dlopened into the host process,
 * Every frame getsenv is an unnecessary expense. */
static int dmd_log_enabled = -1;

void dmd_log(const char *fmt, ...)
{
    if (dmd_log_enabled < 0) {
        const char *env = getenv("DMD_VA_LOG");
        dmd_log_enabled = (env && env[0] == '1') ? 1 : 0;
    }
    if (!dmd_log_enabled)
        return;

    va_list ap;
    va_start(ap, fmt);
    /* Write only:stdout is a host program and triver is not contaminated. */
    fputs("[dmd-va] ", stderr);
    vfprintf(stderr, fmt, ap);
    va_end(ap);
}

struct dmd_driver *dmd_get_driver(VADriverContextP ctx)
{
    if (!ctx || !ctx->pDriverData)
        return NULL;
    return (struct dmd_driver *)ctx->pDriverData;
}

VAStatus dmd_Terminate(VADriverContextP ctx)
{
    if (!ctx)
        return VA_STATUS_ERROR_INVALID_PARAMETER;

    struct dmd_driver *drv = dmd_get_driver(ctx);
    if (!drv) {
        /* After the init midway failed, libva may still be moved here and must return safely. */
        return VA_STATUS_SUCCESS;
    }

    dmd_log("Terminate\n");

    /* Stop backstage line: it touches contexts/frames,
     * You must exit before you can recover these objects below. You cannot hold a lock (to join) on stop. */
    dmd_reaper_stop(drv);

    /* Release of all targets: Consumers should have destroyed themselves, but not under the abnormal exit path.
     * Driver is dlclose and the memory can't be recycled again, so it has to be here.
     *
     * The order is correct: context first (it holds V4L2 sessions and devices fd) and then it is the first to be removed.
     * Undo the image (possibly using the surface buffer), and finally the surface with the buffer. */
    pthread_mutex_lock(&drv->lock);

    int leaked_ctx = 0, leaked_surf = 0, leaked_buf = 0, leaked_img = 0;

    for (int i = 0; i < DMD_MAX_CONTEXTS; i++) {
        if (drv->contexts[i].in_use) {
            leaked_ctx++;
            dmd_context_reset_locked(&drv->contexts[i]);
        }
        /* Hang here for the last person to use. The frame line is already running.
         * No one will return it again io_busy, wait — just unbrush it, or these fds will be
         * The V4L2 session is permanently leaked (driver is dlclose and nobody returns it).
         * There's another thread that's actually going to be UAF here, but that's "process disease exit."
         * Worse than the leak, the situation on the Destroy Context side has been addressed. */
        if (drv->io_defer[i]) {
            dmd_log("Terminate: slot %d And then I’m gonna have a session with a delay in the destruction.\n", i);
            dmd_session_destroy(drv->io_defer[i]);
            drv->io_defer[i] = NULL;
        }
        if (drv->encode_defer[i]) {
            dmd_encode_destroy(drv->encode_defer[i]);
            drv->encode_defer[i] = NULL;
        }
    }
    for (int i = 0; i < DMD_MAX_IMAGES; i++) {
        struct dmd_image *img = &drv->images[i];
        if (!img->in_use)
            continue;
        leaked_img++;
        if (img->map_sync_started && img->derived_from != VA_INVALID_ID) {
            struct dmd_surface *parent = dmd_find_surface_locked(drv, img->derived_from);
            if (parent && parent->dumb_sync_fd >= 0) {
                struct dma_buf_sync sync = {
                    .flags = DMA_BUF_SYNC_END | DMA_BUF_SYNC_READ | DMA_BUF_SYNC_WRITE
                };
                ioctl(parent->dumb_sync_fd, DMA_BUF_IOCTL_SYNC, &sync);
            }
        }
        /* Acquired PRIME descriptors remain driver-owned until Release.
         * Termination also closes them when a client omits that call. */
        if (img->handle_acquired && img->acquired_fd >= 0)
            close(img->acquired_fd);
        /* The derive Image borrows the surface buffer, cannot repeat free. */
        if (img->derived_from == VA_INVALID_ID)
            free(img->data);
        memset(img, 0, sizeof(*img));
    }
    for (int i = 0; i < DMD_MAX_SURFACE_OBJECTS; i++) {
        if (drv->surfaces[i].in_use) {
            leaked_surf++;
            dmd_surface_reset_locked(&drv->surfaces[i]);
        }
    }
    for (int i = 0; i < DMD_MAX_BUFFERS; i++) {
        if (drv->buffers[i].in_use) {
            leaked_buf++;
            free(drv->buffers[i].data);
            memset(&drv->buffers[i], 0, sizeof(drv->buffers[i]));
        }
    }
    pthread_mutex_unlock(&drv->lock);

    if (leaked_ctx || leaked_surf || leaked_buf || leaked_img)
        dmd_log("Terminate: Recover context=%d surface=%d buffer=%d image=%d"
                "(Consumers did not destroy themselves)\n",
                leaked_ctx, leaked_surf, leaked_buf, leaked_img);

    pthread_cond_destroy(&drv->io_done);
    pthread_mutex_destroy(&drv->lock);
    free(drv);
    ctx->pDriverData = NULL;

    return VA_STATUS_SUCCESS;
}

