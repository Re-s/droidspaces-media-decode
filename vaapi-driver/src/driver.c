/* DroidSpaces MediaCodec VA-API triver - entrance and vtable assembly
 *
 * (a) No-sense discovery mechanism (the real-life evidence conclusion would be directly invalid):
 *   1. Libva takes the kernel driver "msm_drm" from /dev/dri/ REDERD128 with DRM_IOCTL_VERSION
 *   2. The DRM ⁇ VA driver map of libva (map[] of v/drm/va_drm_utils.c) does not have msm entries,
 *      So the fallback is for "symptomatic use of kernel driver."
 *   Libva tried only one filename, no fallback:
 *      /usr/lib/aarch64-linux-gnu/dri/msm_drm_drv_video.so
 * So the product must be called msm_drm_drv_video.so, and then put it on the directory.
 * Vainfo/ ffmpeg/ Firefox will automatically find it without any environmental variables.
 *
 * The entry symbol name is generated by VA_DRIVER_ICIT_FUNC macro by header version (currently expanded as
 * ⁇ vaDriverInit_1_22.libva tries to try one by one from the current version.  ⁇ vaDriverInit_1_N.
 * The macro instead of the hard encoding can be automatically followed by libva upgrades.
 */

