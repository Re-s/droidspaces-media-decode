/* The entry symbol must be _vaDriverInit_<major>_minor>. The libva header file does not provide the generation
 * The name's macro (verified va_backend.h only typedef VADRIVERInit), so spell it yourself.
 *
 * Version selection: libva from its own version 1.N**downsequence**dlsym to 1.0 per dlsym
 * (va/va.c of va_getDriverInitName + comptible_versions) with first hits on the mark.
 * Therefore the most wide compatible window to export _vaDriverInit_1_0 - any libva 1.x is acceptable;
 * Export only 1_22 is not hit when libva is below 1.22.
 * Both export at zero cost: one version of the translation (following the headline), one _ 0 (maintaining).
 *
 * -Fvisibility=hidden must display the default visibility, otherwise the symbol will not be exported,
 * Libva will report "has no fun action _vaDriverInit_1_0". */
#define DMD_CONCAT_(a, b, c) a##b##_##c
#define DMD_INIT_NAME_(maj, min) DMD_CONCAT_(__vaDriverInit_, maj, min)
#define DMD_DRIVER_INIT DMD_INIT_NAME_(VA_MAJOR_VERSION, VA_MINOR_VERSION)

static VAStatus dmd_driver_init(VADriverContextP ctx);

__attribute__((visibility("default"))) VAStatus
DMD_DRIVER_INIT(VADriverContextP ctx)
{
    return dmd_driver_init(ctx);
}

/* The secure entry: allows libva, which is below the compilation version, to load the script as well.
 * If the header file is 1.0 itself, the macro above is expanded to the same function, no more definitions are repeated here. */
