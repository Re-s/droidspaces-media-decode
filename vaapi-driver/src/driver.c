static VAStatus dmd_driver_init(VADriverContextP ctx)
{
    if (!ctx || !ctx->vtable)
        return VA_STATUS_ERROR_INVALID_PARAMETER;

    struct dmd_driver *drv = calloc(1, sizeof(*drv));
    if (!drv)
        return VA_STATUS_ERROR_ALLOCATION_FAILED;

    if (pthread_mutex_init(&drv->lock, NULL) != 0) {
        free(drv);
        return VA_STATUS_ERROR_ALLOCATION_FAILED;
    }
    if (pthread_cond_init(&drv->io_done, NULL) != 0) {
        pthread_mutex_destroy(&drv->lock);
        free(drv);
        return VA_STATUS_ERROR_ALLOCATION_FAILED;
    }

    /* The type of ID is not issued to the caller from 1 onwards.
     * Tables use separate ID space, but the buff_id of image borrows the buffer space --
     * MapBuffer is to be able to check in two tables simultaneously with one ID (see description of the image.c). */
    drv->next_config_id = 1;
    drv->encode_caps = dmd_v4l2_enc_probe();
    drv->next_surface_id = 1;
    drv->next_context_id = 1;
    drv->next_buffer_id = 1;
    drv->next_image_id = 1;

    /* Drm_state filled by libva (display_type 0x31 = DRM_ReDERNODES).
     * Only fd is currently recorded, and decoding path is only used when you access it. */
    drv->drm_fd = -1;
    if (ctx->drm_state) {
        const struct drm_state *drm = (const struct drm_state *)ctx->drm_state;
        drv->drm_fd = drm->fd;
    }

    ctx->pDriverData = drv;

    /* Libva to version_major/minor is 0/0, and triver must fill it out itself. */
    ctx->version_major = VA_MAJOR_VERSION;
    ctx->version_minor = VA_MINOR_VERSION;

    /* These 5 max fields must be all > 0 (CCHEK_MAXIMUM of va/ va.c).
     * And the consumer allocates the query array accordingly, must > = the amount we actually return. */
    ctx->max_profiles = DMD_MAX_PROFILES;
    ctx->max_entrypoints = DMD_MAX_ENTRYPOINTS;
    ctx->max_attributes = DMD_MAX_CONFIG_ATTRIBUTES;
    ctx->max_image_formats = DMD_MAX_IMAGE_FORMATS;
    ctx->max_subpic_formats = DMD_MAX_SUBPIC_FORMATS;
    ctx->max_display_attributes = DMD_MAX_DISPLAY_ATTRIBUTES;

    /* Str_vendor must not be NULL (CHECK_STRING).
     * Note that ffmpeg matches the list of vaapi_driver_quirks with this string;
     * We're not on the list. Go standard behaviour. */
    ctx->str_vendor = DMD_VENDOR_STRING;

    dmd_init_vtable(ctx->vtable);
    if (ctx->vtable_vpp) {
        ctx->vtable_vpp->vaQueryVideoProcFilters = dmd_vpp_query_filters;
        ctx->vtable_vpp->vaQueryVideoProcFilterCaps = dmd_vpp_query_filter_caps;
        ctx->vtable_vpp->vaQueryVideoProcPipelineCaps =
            dmd_vpp_query_pipeline_caps;
    }

    /* Display_type in VADRIVerContext is unsigned long, with %lx. */
    dmd_log("init: display_type=0x%lx drm_fd=%d va=%d.%d vendor=%s\n",
            (unsigned long)ctx->display_type, drv->drm_fd, ctx->version_major,
            ctx->version_minor, ctx->str_vendor);

    return VA_STATUS_SUCCESS;
}
