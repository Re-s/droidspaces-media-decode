#!/usr/bin/env python3
"""Generate VA-API vtable stubs and assignments from vtable.json.

libva checks 39 vtable slots during vaInitialize. A null slot aborts
initialization and unloads the driver. Point unimplemented slots to
stubs returning VA_STATUS_ERROR_UNIMPLEMENTED.

Generate stubs.c and stubs.h for unimplemented entry points and
vtable.inc for all assignments. Slots in IMPLEMENTED reference the real
driver functions, named dmd_<entry point without the va prefix>.
"""
import json
import sys

# Generate stubs for entry points outside this set.
IMPLEMENTED = {
    "vaTerminate",
    "vaQueryConfigProfiles",
    "vaQueryConfigEntrypoints",
    "vaGetConfigAttributes",
    "vaCreateConfig",
    "vaDestroyConfig",
    "vaQueryConfigAttributes",
    "vaQuerySurfaceAttributes",
    "vaQueryImageFormats",
    "vaQueryDisplayAttributes",
    "vaGetDisplayAttributes",
    "vaSetDisplayAttributes",
    "vaQuerySubpictureFormats",
    # ---- Decode data path (decode.c) ----
    "vaCreateSurfaces",
    "vaCreateSurfaces2",
    "vaDestroySurfaces",
    "vaCreateContext",
    "vaDestroyContext",
    "vaCreateBuffer",
    "vaBufferSetNumElements",
    "vaMapBuffer",
    # libva falls back to vaMapBuffer only if vaMapBuffer2 is null. A stub
    # here would break FFmpeg readback.
    "vaMapBuffer2",
    "vaUnmapBuffer",
    "vaDestroyBuffer",
    "vaBufferInfo",
    "vaBeginPicture",
    "vaRenderPicture",
    "vaEndPicture",
    "vaSyncSurface",
    "vaSyncSurface2",
    "vaSyncBuffer",
    "vaQuerySurfaceStatus",
    # ---- VAImage exports (image.c) ----
    "vaCreateImage",
    "vaDeriveImage",
    "vaDestroyImage",
    "vaGetImage",
    "vaPutImage",
    # ---- DMA-BUF exports (export.c) ----
    # Firefox CreateImageVAAPI needs a DRM_PRIME_2 descriptor. Export failure
    # falls back to software decoding for the stream.
    "vaExportSurfaceHandle",
}

funcs = json.load(open(sys.argv[1], encoding="utf-8"))


def impl_name(va_name: str) -> str:
    """vaQueryConfigProfiles -> dmd_QueryConfigProfiles"""
    assert va_name.startswith("va")
    return "dmd_" + va_name[2:]


def render_params(params):
    """Render the parameter list. The function body handles unused parameters."""
    if not params:
        return "void"
    out = []
    for p in params:
        t = p["type"]
        # Match the driver style for pointer declarations.
        sep = "" if t.endswith("*") else " "
        out.append(f"{t}{sep}{p['name']}{p['array']}")
    return ", ".join(out)


# ---------- stubs.c ----------
lines = [
    "/* Generated by tools/gen_stubs.py. Do not edit manually.",
    " *",
    " * libva validates the vtable in vaInitialize (va/va.c CHECK_VTABLE).",
    " * A null slot fails initialization. Unimplemented entry points return",
    " * VA_STATUS_ERROR_UNIMPLEMENTED.",
    " */",
    "",
    '#include "driver.h"',
    "",
]

stub_names = []
for f in funcs:
    if f["name"] in IMPLEMENTED:
        continue
    name = impl_name(f["name"])
    stub_names.append((f["name"], name))
    lines.append(f"{f['ret']} {name}({render_params(f['params'])})")
    lines.append("{")
    for p in f["params"]:
        lines.append(f"    (void){p['name']};")
    # Log calls to unimplemented entry points. Clients can silently fall
    # back to software decoding, so the driver log helps diagnose them.
    lines.append(f'    dmd_log("Unimplemented entry point called: {f["name"]}\\n");')
    lines.append("    return VA_STATUS_ERROR_UNIMPLEMENTED;")
    lines.append("}")
    lines.append("")

with open("out/stubs.c", "w", encoding="utf-8") as fh:
    fh.write("\n".join(lines))

# ---------- stubs.h ----------
hl = [
    "/* Generated by tools/gen_stubs.py. Do not edit manually. */",
    "",
    "#ifndef DMD_STUBS_H",
    "#define DMD_STUBS_H",
    "",
    '#include <va/va_backend.h>',
    "",
]
for va_name, name in stub_names:
    f = next(x for x in funcs if x["name"] == va_name)
    hl.append(f"{f['ret']} {name}({render_params(f['params'])});")
hl += ["", "#endif /* DMD_STUBS_H */", ""]
with open("out/stubs.h", "w", encoding="utf-8") as fh:
    fh.write("\n".join(hl))

# ---------- vtable.inc ----------
vl = [
    "/* Generated by tools/gen_stubs.py. Do not edit manually.",
    " * Assign all %d VADriverVTable slots from va_backend.h." % len(funcs),
    " */",
    "",
]
for f in funcs:
    name = f["name"]
    if name == "vaMapBuffer2":
        vl.append("#if VA_CHECK_VERSION(1, 22, 0)")
    vl.append(f"    vtable->{name} = {impl_name(name)};")
    if name == "vaMapBuffer2":
        vl.append("#endif")
vl.append("")
with open("out/vtable.inc", "w", encoding="utf-8") as fh:
    fh.write("\n".join(vl))

print(f"Slots: {len(funcs)} total, {len(funcs)-len(stub_names)} implemented, {len(stub_names)} stubs")
