/*
 * dmd-probe —— decode-daemon 端点探活工具（供 KSU 守护模块使用）
 *
 * 为什么不用 kill(pid,0)：
 *   1) 僵尸进程 kill(pid,0) 仍返回 0，看起来"活着"
 *   2) daemon 有会话级失效模式（SHM 交接失败等）——进程活着、持着 flock，
 *      但已不能服务新会话。进程级判据看不见这一类。
 *
 * 为什么"握手成功"也不够（本文件从"验证握手"改成"验证出帧"的原因）：
 *   真机上出现过一类故障：daemon 进程活着、握手秒回 status=0，却**一帧都
 *   解不出来**。病因是 Unix socket 缓冲容量不足导致上行吞吐塌陷 ——
 *   daemon 读 NALU 跟不上，MediaCodec 输入缓冲填不满，5 秒后放弃会话，
 *   驱动向上报解码失败，容器内浏览器**静默回落 CPU 软解**。
 *   而 watchdog 全程报 healthy，永远不会重启。daemon 日志里旧探针留下的
 *   痕迹一看就知道它什么也没验证：
 *       [1530] 握手成功: video/avc 640x480 帧回传=内联
 *       [1530] 会话结束: 收到 0 NALU, 回传 0 帧
 *   所以现在探针内嵌一小段真实 H.264 码流，送进去并要求**至少收到 1 帧**
 *   回传才判健康。判据从"端点应答"升级成"整条解码链路出帧"。
 *
 * 退出码（守护脚本按此分流）：
 *   0 = 健康（握手 + 至少 1 帧真实回传）
 *   1 = 端点不存在 / connect 失败（daemon 没在跑，或 socket 是死引用）
 *   2 = 连上了但握手失败/被拒（进程活着却不服务 —— 需要重启它）
 *   3 = 参数错误
 *   7 = endpoint inode 不匹配（连上的不是这个端点，挂载配置问题，重启 daemon 无用）
 *   8 = 握手成功但 0 帧回传（新增：正是上面那类"看起来健康、实际不出帧"的故障）
 *
 *   注：现版 dmd-watchdog.sh 只显式分流 0/1/2/7，8 会落到它的
 *   "未知码，按失败处理"分支 —— 计入失败计数但不触发重启。要让它按需重启
 *   得单独改看护脚本（本次不动 dmd-watchdog.sh），日志里会留下可行动的记录。
 *
 * 协议（与 src/decode-daemon.c 保持一致）：
 *   上行握手 24B 大端 [magic][ver][codec][w][h][xfer]
 *   下行响应 12B [status][实际 xfer][namelen]，v3 下 namelen 的 bit31 置位时
 *            其后追加 16B endpoint dev/ino（各拆成高低两个大端 u32）
 *   上行数据 [4B NALU 长度][NALU 数据]（每个长度前缀里只放**单个**带起始码的 NALU）
 *   下行帧   [4B 宽][4B 高][4B 帧大小]([4B 输入单元序号])[NV12 数据]
 *            第 4 字段仅当格式描述块声明 CAP_FRAME_PTS 时存在
 *   格式块   [4B 0][4B 能力位][4B 0xFFFFFFFF] + 32B 内容（哨兵帧头引出）
 */
