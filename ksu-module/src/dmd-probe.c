static long long now_ms(void)
{
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (long long)ts.tv_sec * 1000 + ts.tv_nsec / 1000000;
}

/* 带绝对截止时间的全量读写：守护进程里绝不能因为对端半死而永久阻塞。
 * 用**绝对 deadline** 而不是每次调用给一个相对超时 —— 否则"每步 3 秒"
 * 累加起来能拖到十几秒，看护的 5 秒轮询就会被自己的探针挤掉。 */
static int io_all(int fd, void *buf, size_t len, int writing, long long deadline)
{
    unsigned char *p = buf;
    size_t done = 0;
    while (done < len) {
        long long left = deadline - now_ms();
        if (left <= 0)
            return IO_TIMEOUT;
        struct pollfd pfd = { .fd = fd, .events = writing ? POLLOUT : POLLIN };
        int pr = poll(&pfd, 1, (int)left);
        if (pr == 0)
            return IO_TIMEOUT;
        if (pr < 0) {
            if (errno == EINTR)
                continue;
            return IO_ERR;
        }
        ssize_t n = writing ? write(fd, p + done, len - done)
                            : read(fd, p + done, len - done);
        if (n > 0) {
            done += (size_t)n;
            continue;
        }
        if (n == 0)
            return done ? IO_ERR : IO_EOF;   /* 半条消息 = 异常；边界 = 正常收尾 */
        if (errno == EINTR || errno == EAGAIN)
            continue;
        return IO_ERR;
    }
    return IO_OK;
}

static int read_all(int fd, void *buf, size_t len, long long deadline)
{
    return io_all(fd, buf, len, 0, deadline);
}

/* 写路径不会修改缓冲，const 剥离集中在这里做一次，免得散落到调用点 */
static int write_all(int fd, const void *buf, size_t len, long long deadline)
{
    return io_all(fd, (void *)(uintptr_t)buf, len, 1, deadline);
}

static const char *io_why(int rc)
{
    switch (rc) {
    case IO_TIMEOUT: return "超时";
    case IO_EOF:     return "对端关闭连接";
    default:         return "读写出错";
    }
}

/* 定位下一个 3 字节起始码 00 00 01（4 字节起始码的后三字节同样命中），
 * 找不到返回 len。 */
static size_t next_start_code(const unsigned char *d, size_t len, size_t from)
{
    for (size_t i = from; i + 2 < len; i++)
        if (d[i] == 0 && d[i + 1] == 0 && d[i + 2] == 1)
            return i;
    return len;
}

/*
 * 把内嵌码流按起始码切成单个 NALU，逐个加 4 字节长度前缀发出。
 *
 * ⚠️ 不能整块发。协议规定一个长度前缀里只放**一个** NALU，而 daemon 要靠
 * 逐个判类型才能把 SPS(7)/PPS(8) 认出来累积成 CSD（用 BUFFER_FLAG_CODEC_CONFIG
 * 送入，这类单元本身不产出帧）。整块发会被当成一个巨型 VCL 单元，
 * 结果是解码器没有参数集、一帧也出不来 —— 恰好是我们要抓的故障的假阳性。
 * NALU 必须**带起始码**（3 或 4 字节都行），daemon 的 nalu_type() 会跳过它。
 */
static int send_stream(int fd, long long deadline, unsigned *nalus, int *rc_out)
{
    const unsigned char *d = probe_stream;
    const size_t len = sizeof(probe_stream);
    size_t pos = next_start_code(d, len, 0);

    *nalus = 0;
    while (pos < len) {
        size_t next = next_start_code(d, len, pos + 3);
        size_t end = next;
        /* 剥掉尾部的 0x00：它们要么是下一个 4 字节起始码的首字节，要么是
         * trailing_zero_8bits。RBSP 末尾必有 stop bit（非 0 字节），
         * 所以剥零不会碰到语义内容。不剥的后果是把下个起始码的前导零
         * 挂在上一个 NALU 尾部 —— 多数解码器容忍，但没必要冒这个风险。 */
        while (end > pos + 3 && d[end - 1] == 0)
            end--;

        uint32_t nl = htonl((uint32_t)(end - pos));
        int rc = write_all(fd, &nl, 4, deadline);
        if (rc == IO_OK)
            rc = write_all(fd, d + pos, end - pos, deadline);
        if (rc != IO_OK) {
            *rc_out = rc;
            return -1;
        }
        (*nalus)++;
        pos = next;
    }
    return 0;
}

/*
 * 读下行，数出真实帧。
 *
 * 一套解析逻辑覆盖两种消息：帧大小字段等于哨兵 0xFFFFFFFF 就是格式描述块
 * （合法帧大小不可能取到这个值），否则是帧。格式块头部第 2 个字是能力位，
 * 置了 CAP_FRAME_PTS 说明后续每个帧头多一个第 4 字段（输入单元序号）；
 * 旧 daemon 那里恒为 0，按 3 字段解析 —— 这是唯一正确的判据，不能靠猜。
 */
static int collect_frames(int fd, long long hard_deadline, unsigned *frames,
                          int *rc_out, const char **desync)
{
    uint32_t caps = 0;
    unsigned char sink[DISCARD_CHUNK];

    *frames = 0;
    for (;;) {
        /* 收到首帧之后就已经能判健康了，剩下的时间只用来把帧数数完整，
         * 因此改用一个短得多的截止时间，绝不把看护的轮询间隔耗光。 */
        long long deadline = hard_deadline;
        if (*frames > 0) {
            long long grace = now_ms() + TAIL_GRACE_MS;
            if (grace < deadline)
                deadline = grace;
        }

        uint32_t head[3];
        int rc = read_all(fd, head, sizeof(head), deadline);
        if (rc != IO_OK) {
            if (*frames > 0)
                return 0;             /* 已经出过帧，收尾怎么结束都无所谓 */
            *rc_out = rc;
            return -1;
        }

        uint32_t fsz = ntohl(head[2]);

        if (fsz == FMTDESC_SENTINEL) {
            unsigned char body[FMTDESC_BYTES];
            rc = read_all(fd, body, sizeof(body), deadline);
            if (rc != IO_OK) {
                if (*frames > 0)
                    return 0;
                *rc_out = rc;
                return -1;
            }
            caps = ntohl(head[1]);
            continue;
        }

        if (fsz == SHMFRAME_SENTINEL) {
            /* 我们握手时请求的是内联模式（xfer=0），daemon 只会降级不会升级，
             * 所以这里出现 SHM 帧通知只能是协议错位 —— 继续解析毫无意义。 */
            *desync = "内联模式收到 SHM 帧通知";
            *rc_out = IO_ERR;
            return -1;
        }

        if (caps & CAP_FRAME_PTS) {
            uint32_t pts;
            rc = read_all(fd, &pts, sizeof(pts), deadline);
            if (rc != IO_OK) {
                if (*frames > 0)
                    return 0;
                *rc_out = rc;
                return -1;
            }
        }

        if (fsz > FRAME_SANITY_MAX) {
            *desync = "下行帧大小离谱，协议错位";
            *rc_out = IO_ERR;
            return -1;
        }

        size_t rem = fsz;
        while (rem > 0) {
            size_t ch = rem > sizeof(sink) ? sizeof(sink) : rem;
            rc = read_all(fd, sink, ch, deadline);
            if (rc != IO_OK) {
                if (*frames > 0)
                    return 0;
                *rc_out = rc;
                return -1;
            }
            rem -= ch;
        }

        if (fsz > 0) {
            /* 只有"帧大小 > 0 的非哨兵消息"才算真出帧 —— 格式块、空消息都不算。 */
            (*frames)++;
            if (*frames >= 64)
                return 0;             /* 数够了，别陪 daemon 无限跑下去 */
        }
    }
}

static int connect_endpoint(const struct sockaddr_un *ua)
{
    int fd = socket(AF_UNIX, SOCK_STREAM | SOCK_CLOEXEC, 0);
    if (fd < 0) {
        fprintf(stderr, "probe: socket(): %s\n", strerror(errno));
        return -1;
    }
    if (connect(fd, (const struct sockaddr *)ua, sizeof(*ua)) != 0) {
        /* 目录级挂载下这通常意味着 daemon 真的没在跑；
         * 文件级挂载下也可能是挂载钉着死 inode（那要修挂载，不是重启 daemon）。 */
        fprintf(stderr, "probe: connect 失败: %s\n", strerror(errno));
        close(fd);
        return -1;
    }
    return fd;
}

int main(int argc, char **argv)
{
    if (argc < 2) {
        fprintf(stderr, "用法: dmd-probe <socket 路径> [超时毫秒，默认 3000]\n");
        return 3;
    }
    const char *path = argv[1];
    int timeout_ms = (argc > 2) ? atoi(argv[2]) : 3000;
    if (timeout_ms <= 0)
        timeout_ms = 3000;

    /* 真解码比纯握手慢，但 96x96 五个 IDR 在几十毫秒量级；超时仍由调用方
     * 一个参数封顶，所有 I/O 共享这一个绝对截止时间。 */
    long long t0 = now_ms();
    long long deadline = t0 + timeout_ms;

    struct stat st;
    if (stat(path, &st) != 0) {
        fprintf(stderr, "probe: 端点不存在 %s: %s\n", path, strerror(errno));
        return 1;
    }

    struct sockaddr_un ua;
    memset(&ua, 0, sizeof(ua));
    ua.sun_family = AF_UNIX;
    if (strlen(path) >= sizeof(ua.sun_path)) {
        fprintf(stderr, "probe: 路径过长\n");
        return 3;
    }
    memcpy(ua.sun_path, path, strlen(path));

    int fd = connect_endpoint(&ua);
    if (fd < 0)
        return 1;

    uint32_t hello[6] = {
        htonl(HELLO_MAGIC), htonl(HELLO_VERSION), htonl(0),   /* codec 0 = H.264 */
        htonl(PROBE_W), htonl(PROBE_H), htonl(0)              /* xfer 0 = 内联 */
    };
    /* 传输模式固定用内联：SHM 要另开 abstract socket 去收 memfd，
     * 对"能不能出帧"这个判据没有任何增量，只会给探针加一条易碎的路径。 */
    if (write_all(fd, hello, sizeof(hello), deadline) != IO_OK) {
        fprintf(stderr, "probe: 发送握手失败/超时\n");
        close(fd);
        return 2;
    }

    uint32_t head[3];
    if (read_all(fd, head, sizeof(head), deadline) != IO_OK) {
        fprintf(stderr, "probe: 未收到握手响应/超时（进程可能活着但不服务）\n");
        close(fd);
        return 2;
    }
    uint32_t status = ntohl(head[0]);
    uint32_t nlen_w = ntohl(head[2]);
    int legacy_v2 = 0;

    if (status == 1) {
        /* 旧 daemon 严格判版本会拒 v3。它仍是健康的，只是版本旧，
         * 用 v2 再探一次，避免守护把好 daemon 当坏的杀掉。
         * v2 响应没有 endpoint 扩展，这一轮跳过 inode 对账。 */
        close(fd);
        fd = connect_endpoint(&ua);
        if (fd < 0)
            return 1;
        hello[1] = htonl(2u);
        if (write_all(fd, hello, sizeof(hello), deadline) != IO_OK ||
            read_all(fd, head, sizeof(head), deadline) != IO_OK) {
            fprintf(stderr, "probe: v2 降级重试失败/超时\n");
            close(fd);
            return 2;
        }
        status = ntohl(head[0]);
        nlen_w = ntohl(head[2]);
        legacy_v2 = 1;
    }

    if (status != 0) {
        /* status 非 0 时响应恒为裸 12 字节，随后连接关闭，没有后续可读。 */
        fprintf(stderr, "probe: daemon 拒绝握手 status=%u\n", status);
        close(fd);
        return 2;
    }

    uint32_t xfer = ntohl(head[1]);
    if (xfer != 0) {
        /* 我们只请求了内联，daemon 却给了 SHM：帧不会走这条连接回来，
         * 这个会话不可能出帧，直接判不服务而不是白等一个超时。 */
        fprintf(stderr, "probe: daemon 返回非内联传输模式 %u，探针无法收帧\n", xfer);
        close(fd);
        return 2;
    }

    /* v3 扩展存在时顺手做 inode 对账：不匹配说明连上的不是这个路径背后的
     * 端点，重启 daemon 解决不了（是挂载/配置问题），单独用退出码 7 区分。
     * 注意必须拿 stat(路径) 的结果比对，不能 fstat 连接 fd —— 后者是
     * socket 的匿名 inode，跟监听端点的 inode 毫无关系。 */
    int have_ep = 0;
    unsigned long long ep_dev = 0, ep_ino = 0;
    if (!legacy_v2 && (nlen_w >> 31)) {
        uint32_t ext[4];
        if (read_all(fd, ext, sizeof(ext), deadline) == IO_OK) {
            ep_dev = ((unsigned long long)ntohl(ext[0]) << 32) | ntohl(ext[1]);
            ep_ino = ((unsigned long long)ntohl(ext[2]) << 32) | ntohl(ext[3]);
            if (ep_dev != (unsigned long long)st.st_dev ||
                ep_ino != (unsigned long long)st.st_ino) {
                fprintf(stderr, "probe: endpoint inode 不匹配 "
                        "stat(dev=%llu,ino=%llu) != daemon(dev=%llu,ino=%llu)\n",
                        (unsigned long long)st.st_dev,
                        (unsigned long long)st.st_ino, ep_dev, ep_ino);
                close(fd);
                return 7;
            }
            have_ep = 1;
        } else {
            fprintf(stderr, "probe: endpoint 扩展读取失败，跳过 inode 对账\n");
        }
    }

    /* 内联模式下名字长度恒为 0；万一不是（协议演进/异常），必须把这些字节
     * 吃掉再往下读，否则后面的帧头会整体错位。 */
    uint32_t nlen = nlen_w & 0x7FFFFFFFu;
    if (nlen > 0 && nlen <= 256) {
        unsigned char name[256];
        if (read_all(fd, name, nlen, deadline) != IO_OK) {
            fprintf(stderr, "probe: 读取端点名字失败\n");
            close(fd);
            return 2;
        }
    } else if (nlen > 256) {
        fprintf(stderr, "probe: 握手响应名字长度异常 %u\n", nlen);
        close(fd);
        return 2;
    }

    /* ---- 到这里握手已完全成功。以下任何"收不到帧"都算新故障类别（退出码 8）---- */
    unsigned nalus = 0, frames = 0;
    int io_rc = IO_ERR;
    const char *desync = NULL;

    if (send_stream(fd, deadline, &nalus, &io_rc) != 0) {
        /* 上行就卡住/断开本身就是那类故障的现场：吞吐塌陷时 daemon 读不动，
         * 我们的 write 先超时；会话被放弃时 write 直接拿到 EPIPE。 */
        fprintf(stderr, "probe: 不健康 握手成功但送码流失败（超时 %dms，"
                "已送 %u 个 NALU，原因=%s）\n",
                timeout_ms, nalus, io_why(io_rc));
        close(fd);
        return 8;
    }

    /* 关写端触发 daemon 送 EOS，解码器把在手的帧全部吐出来。
     * 探针是一次性会话，用不着可逆的排空（长度 0 那条路）—— 那是给
     * 长驻会话准备的，而且 flush 会摧毁参考帧链，对探针纯属副作用。 */
    shutdown(fd, SHUT_WR);

    if (collect_frames(fd, deadline, &frames, &io_rc, &desync) != 0 || frames == 0) {
        if (desync)
            fprintf(stderr, "probe: 不健康 下行解析异常：%s（已送 %u 个 NALU）\n",
                    desync, nalus);
        else
            fprintf(stderr, "probe: 不健康 握手成功但 0 帧回传（超时 %dms，"
                    "已送 %u 个 NALU，原因=%s）\n",
                    timeout_ms, nalus, io_why(io_rc));
        close(fd);
        return 8;
    }

    /* 送入 NALU 数 ≠ 回传帧数，别拿它们做等式判据：SPS/PPS 不产出帧，
     * 解码器还有排队与重排序延迟。判据只有一条 —— 至少 1 帧真实回传。 */
    if (legacy_v2)
        printf("probe: 健康 帧=%u（协议 v2，旧 daemon）\n", frames);
    else if (have_ep)
        printf("probe: 健康 帧=%u dev=%llu ino=%llu\n", frames, ep_dev, ep_ino);
    else
        printf("probe: 健康 帧=%u（无 endpoint 扩展）\n", frames);

    close(fd);
    return 0;
}
